def normalize_state(name: str | None) -> str | None:
    if not name:
        return None
    key = " ".join(name.replace("&", "and").split()).lower()
    for state in STATE_COORDS:
        if state.lower() == key:
            return state
    if "dadra" in key or "daman" in key:
        return "The Dadra And Nagar Haveli And Daman And Diu"
    if "andaman" in key:
        return "Andaman And Nicobar Islands"
    return None
